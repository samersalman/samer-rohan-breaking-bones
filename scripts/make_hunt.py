"""Build data/hunt.json (the public scavenger hunt file) from scripts/hunt-source.json.

hunt-source.json holds the plain answers and the secret DM phrase. It is git-ignored,
so the answers and phrase never appear in the public repo or the page source.
data/hunt.json keeps only the clues, hints, SHA-256 hashes of the answers, and the phrase
encrypted with the answers (the browser can only decrypt it after all answers are right).

Usage:  python3 -I scripts/make_hunt.py
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "scripts" / "hunt-source.json"
OUT = ROOT / "data" / "hunt.json"
PAPERS = ROOT / "data" / "papers.json"


def norm(v):
    m = re.search(r"\d+(\.\d+)?", str(v).replace(",", ""))
    return m.group(0) if m else ""


def sha(s):
    return hashlib.sha256(s.encode("utf-8")).digest()


def main():
    src = json.loads(SRC.read_text(encoding="utf-8"))
    answers = [norm(s["answer"]) for s in src["steps"]]
    if not all(answers):
        sys.exit("Every answer must contain a number.")

    # Warn if an answer no longer appears in a public summary for its month.
    papers = json.loads(PAPERS.read_text(encoding="utf-8"))["papers"]
    for i, s in enumerate(src["steps"]):
        texts = [str(p.get("summary", "")) for p in papers
                 if p.get("month") == s["month"] and p.get("reviewed") and not p.get("hidden")]
        if not any(re.search(r"(?<![\d.,])" + re.escape(answers[i]) + r"(?![\d])", t.replace(",", "")) for t in texts):
            print(f"WARNING: clue {i + 1}: answer not found in any public summary for month {s['month']}")

    phrase = src["phrase"].encode("utf-8")
    key = b"".join(sha("bb-hunt-final|" + "|".join(answers) + "|" + str(j)) for j in range((len(phrase) + 31) // 32))
    cipher = bytes(a ^ b for a, b in zip(phrase, key))

    out = {
        "note": "Generated by scripts/make_hunt.py. Do not edit by hand.",
        "dm": src.get("dm", "https://ig.me/m/breakkingbones"),
        "steps": [
            {"month": s["month"], "clue": s["clue"], "hints": s["hints"],
             "hash": sha(f"bb-hunt|{i}|{answers[i]}").hex()}
            for i, s in enumerate(src["steps"])
        ],
        "final": cipher.hex(),
    }
    OUT.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} with {len(out['steps'])} clues.")


if __name__ == "__main__":
    main()
